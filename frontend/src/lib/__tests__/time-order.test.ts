import { expect, it } from "vitest";
import { compareTimestamps } from "../time-order";

it.each([
  ["2026-10-08T00:00:00.123456789Z", "2026-10-08T00:00:00.123456790Z"],
  ["2026-10-08T00:00:00.12Z", "2026-10-08T00:00:00.120000001Z"],
  ["2026-10-08T00:00:00Z", "2026-10-08T00:00:00.000000001Z"],
  ["2026-10-08T00:00:00.999999999Z", "2026-10-08T00:00:01Z"],
  ["2026-10-08T01:00:00.123456789+01:00", "2026-10-08T00:00:00.123456790Z"],
  ["2026-10-07T19:00:00.123456789-05:00", "2026-10-08T00:00:00.123456790Z"],
])("比较 %s 与 %s 时保持实际先后顺序", (older, newer) => {
  expect(compareTimestamps(older, newer)).toBeLessThan(0);
  expect(compareTimestamps(newer, older)).toBeGreaterThan(0);
});

it.each([
  ["2026-10-08T01:00:00.123456789+01:00", "2026-10-08T00:00:00.123456789Z"],
  ["2026-10-08T00:00:00.12Z", "2026-10-08T00:00:00.120000000Z"],
  ["2026-10-08T00:00:00Z", "2026-10-08T00:00:00.000000000Z"],
])("等值时间 %s 与 %s 不因时区或小数长度产生排序差异", (first, second) => {
  expect(compareTimestamps(first, second)).toBe(0);
});
